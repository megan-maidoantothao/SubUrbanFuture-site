/* ============================================================
   Council population race, 2010–2024.
   One chart on the Melbourne page, all 35 councils, coloured by
   growth-area status. Two view modes: raw population (who's
   biggest) and percentage growth since 2010 (who's growing
   fastest, independent of size). Reads
   assets/data/melbourne/council-population.json
   (generated by prepare_data.R).
   ============================================================ */
(() => {
  const container = document.querySelector("#growth-area-race");
  if (!container || typeof d3 === "undefined") return;

  const source = container.dataset.source;
  const tooltip = d3.select("#growth-area-race-tooltip");
  const STEPS_PER_YEAR = 8;
  const STEP_MS = 110;
  const establishedColour = "#2a78d6";
  const growthColour = "#eb6834";

  const dataPromise = window.SUBURBAN_FUTURES_COUNCIL_POPULATION
    ? Promise.resolve(window.SUBURBAN_FUTURES_COUNCIL_POPULATION)
    : d3.json(source);

  dataPromise.then(({ years, rows }) => {
    const fallback = container.querySelector(".static-fallback");

    const byYear = d3.group(rows, (d) => d.year);
    const councils = Array.from(new Set(rows.map((d) => d.council)));
    const growthArea = new Map(rows.map((d) => [d.council, d.growth_area]));
    const baseYear = years[0];
    const baseValues = new Map(byYear.get(baseYear).map((d) => [d.council, d.population]));

    // Build interpolated keyframes between each pair of adjacent years so
    // the bars move smoothly instead of jumping year to year. Each frame
    // carries both the raw value and the % change since baseYear, so
    // switching view mode doesn't need new data or a restart.
    function makeFrame(year, valueOf) {
      return {
        year,
        raw: councils
          .map((council) => ({ council, metric: valueOf(council) }))
          .sort((a, b) => d3.descending(a.metric, b.metric)),
        growth: councils
          .map((council) => ({
            council,
            metric: (valueOf(council) - baseValues.get(council)) / baseValues.get(council)
          }))
          .sort((a, b) => d3.descending(a.metric, b.metric))
      };
    }

    const keyframes = [];
    for (let i = 0; i < years.length - 1; i++) {
      const y0 = years[i];
      const y1 = years[i + 1];
      const v0 = new Map(byYear.get(y0).map((d) => [d.council, d.population]));
      const v1 = new Map(byYear.get(y1).map((d) => [d.council, d.population]));
      for (let s = 0; s < STEPS_PER_YEAR; s++) {
        const t = s / STEPS_PER_YEAR;
        const yearLabel = y0 + (y1 - y0) * t;
        keyframes.push(
          makeFrame(yearLabel, (council) => v0.get(council) + (v1.get(council) - v0.get(council)) * t)
        );
      }
    }
    const lastYear = years[years.length - 1];
    const lastValues = new Map(byYear.get(lastYear).map((d) => [d.council, d.population]));
    keyframes.push(makeFrame(lastYear, (council) => lastValues.get(council)));

    const width = 900;
    const barHeight = 20;
    const barGap = 5;
    const margin = { top: 30, right: 100, bottom: 10, left: 130 };
    const height = margin.top + margin.bottom + (barHeight + barGap) * councils.length;

    const x = d3.scaleLinear().range([margin.left, width - margin.right]);
    const y = d3
      .scaleBand()
      .domain(d3.range(councils.length))
      .range([margin.top, height - margin.bottom])
      .padding(0.18);

    const svg = d3
      .create("svg")
      .attr("viewBox", `0 0 ${width} ${height}`)
      .attr("role", "img")
      .attr("aria-label", "Animated bar chart of population by council, Greater Melbourne, 2010 to 2024.");

    const bars = svg.append("g");
    const labels = svg.append("g").attr("font-family", "inherit").attr("font-size", 11);
    const values = svg.append("g").attr("font-family", "inherit").attr("font-size", 10).attr("fill", "#4f5962");

    const yearText = svg
      .append("text")
      .attr("x", width - margin.right)
      .attr("y", height - 24)
      .attr("text-anchor", "end")
      .attr("font-size", 46)
      .attr("font-weight", 700)
      .attr("fill", "#d9d7d0");

    const totalText = svg
      .append("text")
      .attr("x", width - margin.right)
      .attr("y", height - 70)
      .attr("text-anchor", "end")
      .attr("font-size", 13)
      .attr("fill", "#4f5962");

    let mode = "raw"; // "raw" | "growth"
    let currentTotal = 0;

    function colourOf(council) {
      return growthArea.get(council) ? growthColour : establishedColour;
    }

    function seriesOf(frame) {
      return mode === "raw" ? frame.raw : frame.growth;
    }

    function rankOf(frame, council) {
      return seriesOf(frame).findIndex((d) => d.council === council);
    }

    function render(frame) {
      const series = seriesOf(frame);
      const extent = d3.extent(series, (d) => d.metric);
      x.domain(mode === "raw" ? [0, extent[1] * 1.25] : [Math.min(0, extent[0] * 1.1), extent[1] * 1.25]);

      yearText.text(Math.round(frame.year));

      currentTotal = d3.sum(frame.raw, (d) => d.metric);
      totalText.text(`Greater Melbourne total: ${d3.format(",")(Math.round(currentTotal))}`);

      const labelFor = (d) =>
        mode === "raw"
          ? `${d3.format(",")(Math.round(d.metric))} (${d3.format(".1%")(d.metric / currentTotal)})`
          : `${d.metric >= 0 ? "+" : ""}${d3.format(".1%")(d.metric)} since ${baseYear}`;

      bars
        .selectAll("rect")
        .data(series, (d) => d.council)
        .join(
          (enter) =>
            enter
              .append("rect")
              .attr("x", x(0))
              .attr("y", (d) => y(rankOf(frame, d.council)))
              .attr("height", y.bandwidth())
              .attr("width", (d) => Math.abs(x(d.metric) - x(0)))
              .attr("fill", (d) => colourOf(d.council))
              .attr("fill-opacity", 0.9)
              .on("pointermove", (event, d) => showTooltip(event, d))
              .on("pointerleave", () => tooltip.style("opacity", 0)),
          (update) => update
        )
        .attr("y", (d) => y(rankOf(frame, d.council)))
        .attr("x", (d) => Math.min(x(0), x(d.metric)))
        .attr("width", (d) => Math.abs(x(d.metric) - x(0)))
        .attr("fill", (d) => colourOf(d.council));

      labels
        .selectAll("text")
        .data(series, (d) => d.council)
        .join((enter) => enter.append("text").attr("text-anchor", "end").attr("x", margin.left - 8))
        .attr("y", (d) => y(rankOf(frame, d.council)) + y.bandwidth() / 2 + 4)
        .text((d) => d.council);

      values
        .selectAll("text")
        .data(series, (d) => d.council)
        .join((enter) => enter.append("text").attr("text-anchor", "start"))
        .attr("x", (d) => Math.max(x(0), x(d.metric)) + 6)
        .attr("y", (d) => y(rankOf(frame, d.council)) + y.bandwidth() / 2 + 4)
        .text(labelFor);
    }

    function showTooltip(event, d) {
      const label =
        mode === "raw"
          ? `${d3.format(",")(Math.round(d.metric))} people (${d3.format(".1%")(d.metric / currentTotal)} of Greater Melbourne)`
          : `${d.metric >= 0 ? "+" : ""}${d3.format(".1%")(d.metric)} population change since ${baseYear}`;
      tooltip
        .style("opacity", 1)
        .style("left", `${event.pageX + 12}px`)
        .style("top", `${event.pageY + 12}px`)
        .html(`<strong>${d.council}</strong><br>${label}<br>` + (growthArea.get(d.council) ? "Growth area" : "Established"));
    }

    if (fallback) fallback.remove();

    const controls = d3.create("div").attr("class", "mb-2 d-flex flex-wrap align-items-center gap-2");
    const playButton = controls
      .append("button")
      .attr("type", "button")
      .attr("class", "btn btn-sm btn-outline-secondary")
      .text("Pause");

    const modeGroup = controls.append("div").attr("class", "btn-group btn-group-sm").attr("role", "group");
    const rawModeButton = modeGroup
      .append("button")
      .attr("type", "button")
      .attr("class", "btn btn-outline-secondary active")
      .text("Raw numbers");
    const growthModeButton = modeGroup
      .append("button")
      .attr("type", "button")
      .attr("class", "btn btn-outline-secondary")
      .text("Percentage growth");

    const scrubber = controls
      .append("input")
      .attr("type", "range")
      .attr("min", 0)
      .attr("max", keyframes.length - 1)
      .attr("value", 0)
      .attr("class", "form-range flex-grow-1")
      .style("max-width", "260px");

    const modeHint = d3
      .create("p")
      .attr("class", "mb-2")
      .style("font-size", "0.8rem")
      .style("color", "#4f5962")
      .text("Raw numbers: which councils are adding the most people. Switch to percentage growth to compare pace of growth, independent of size.");

    const legend = d3
      .create("div")
      .attr("class", "mb-2")
      .style("font-size", "0.85rem")
      .html(
        `<span style="color:${growthColour}">■</span> Growth areas &nbsp; ` +
        `<span style="color:${establishedColour}">■</span> Established areas`
      );
    container.append(controls.node());
    container.append(modeHint.node());
    container.append(legend.node());
    container.append(svg.node());

    let frameIndex = 0;
    let playing = true;
    let timer = null;

    function goTo(i) {
      frameIndex = Math.max(0, Math.min(keyframes.length - 1, i));
      scrubber.property("value", frameIndex);
      render(keyframes[frameIndex]);
    }

    function setMode(next) {
      mode = next;
      rawModeButton.classed("active", mode === "raw");
      growthModeButton.classed("active", mode === "growth");
      render(keyframes[frameIndex]);
    }

    function tick() {
      if (frameIndex >= keyframes.length - 1) {
        pause();
        return;
      }
      goTo(frameIndex + 1);
    }

    function play() {
      playing = true;
      playButton.text("Pause");
      if (frameIndex >= keyframes.length - 1) goTo(0);
      timer = d3.interval(tick, STEP_MS);
    }

    function pause() {
      playing = false;
      playButton.text("Replay");
      if (timer) timer.stop();
    }

    playButton.on("click", () => {
      if (playing) {
        pause();
        playButton.text("Play");
      } else {
        play();
      }
    });
    scrubber.on("input", (event) => {
      pause();
      playButton.text("Play");
      goTo(+event.target.value);
    });
    rawModeButton.on("click", () => setMode("raw"));
    growthModeButton.on("click", () => setMode("growth"));

    render(keyframes[0]);
    play();
  }).catch((error) => {
    console.error(error);
  });
})();
